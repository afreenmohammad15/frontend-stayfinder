export function getGoogleMapsUrl(lat, lng, name = "") {
  if (name) {
    return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(name + ", Hyderabad")}`;
  }
  return `https://www.google.com/maps/search/?api=1&query=${lat},${lng}`;
}

export function getGoogleMapsDirectionsUrl(destLat, destLng, userLat = null, userLng = null) {
  if (userLat && userLng) {
    return `https://www.google.com/maps/dir/?api=1&origin=${userLat},${userLng}&destination=${destLat},${destLng}&travelmode=driving`;
  }
  return `https://www.google.com/maps/dir/?api=1&destination=${destLat},${destLng}&travelmode=driving`;
}

export function getGoogleMapsEmbedUrl(lat, lng) {
  return `https://maps.google.com/maps?q=${lat},${lng}&hl=en&z=15&output=embed`;
}
